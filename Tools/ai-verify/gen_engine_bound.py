#!/usr/bin/env python3
"""Rebuild engine_bound.txt from a FULL (--all) reference run of the base revision.

    python Tools/ai-verify/gen_engine_bound.py <full-result.xml>

A test goes on the list when it does not pass and its message names a native-engine failure
(MissingMethodException / TypeInitializationException): outside Unity it cannot pass. Every other
failure is NOT listed (a candidate for a real bug) and is printed for the owner instead.
"""
import os, re, sys, xml.etree.ElementTree as ET

ENGINE = ('MissingMethodException', 'TypeInitializationException')
src = sys.argv[1]
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'engine_bound.txt')

engine, other = [], []
cases = list(ET.parse(src).getroot().iter('test-case'))
for t in cases:
    if t.get('result') == 'Passed':
        continue
    m = t.find('.//message')
    text = (m.text or '') if m is not None else ''
    (engine if any(k in text for k in ENGINE) else other).append((t.get('fullname'), text))

names = sorted({n for n, _ in engine})
with open(out, 'w', encoding='utf-8', newline='\n') as f:
    f.write('# Tests that need the native engine: skipped by the fast ai-verify scope.\n')
    f.write('# Generated by gen_engine_bound.py from a --all run; do not edit by hand.\n')
    f.write(''.join(n + '\n' for n in names))

print(f'{len(cases)} tests, {len(engine)} engine-bound -> {out} ({len(names)} names)')
print(f'not engine-bound, failing ({len(other)}) - candidates for real errors:')
for n, text in sorted(other):
    print('  -', n, '->', re.sub(r'\s+', ' ', text).strip()[:200])
